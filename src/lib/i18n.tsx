export const DICTS: Record<Lang, Dict> = { en, "zh-Hant": zhHant, "zh-Hans": zhHans, es, fr, ko };

function detect(): Lang {
  try {
    const saved = localStorage.getItem(STORE_KEY) as Lang | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    /* storage unavailable */
  }
  const nav = (typeof navigator !== "undefined" ? navigator.languages?.[0] || navigator.language : "en").toLowerCase();
  if (nav.startsWith("zh")) return /tw|hk|mo|hant/.test(nav) ? "zh-Hant" : "zh-Hans";
  if (nav.startsWith("es")) return "es";
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("ko")) return "ko";
  return "en";
}

type Ctx = { lang: Lang; t: Dict; setLang: (l: Lang) => void; appUrl: string };
const LangCtx = createContext<Ctx>({ lang: "en", t: en, setLang: () => {}, appUrl: APP_URL });

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    setLangState(detect());
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORE_KEY, l);
    } catch {
      /* storage unavailable */
    }
  };
  return <LangCtx.Provider value={{ lang, t: DICTS[lang], setLang, appUrl: `${APP_URL}/?lang=${lang}` }}>{children}</LangCtx.Provider>;
}

export const useI18n = () => useContext(LangCtx);
